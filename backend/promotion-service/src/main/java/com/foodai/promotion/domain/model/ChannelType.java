package com.foodai.promotion.domain.model;

/**
 * Enumeration of marketing channel types.
 *
 * @author FoodAI Team
 */
public enum ChannelType {
  /** Push notification. */
  PUSH,

  /** SMS message. */
  SMS,

  /** Email communication. */
  EMAIL,

  /** WhatsApp message. */
  WHATSAPP,

  /** In-app banner. */
  BANNER,

  /** Deal of the hour placement. */
  DEAL_OF_HOUR,

  /** Facebook ads. */
  FACEBOOK,

  /** Instagram ads. */
  INSTAGRAM,

  /** Twitter/X ads. */
  TWITTER,

  /** LinkedIn ads. */
  LINKEDIN,

  /** YouTube ads. */
  YOUTUBE
}

