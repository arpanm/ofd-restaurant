package com.foodai.user.domain.model;

/**
 * Enumeration of diet plan types.
 *
 * @author FoodAI Team
 */
public enum DietPlanType {
    /**
     * Weight loss focused plan
     */
    WEIGHT_LOSS,

    /**
     * Weight gain / muscle building plan
     */
    MUSCLE_GAIN,

    /**
     * Maintenance plan
     */
    MAINTENANCE,

    /**
     * Low carb / keto plan
     */
    LOW_CARB,

    /**
     * High protein plan
     */
    HIGH_PROTEIN,

    /**
     * Balanced nutrition plan
     */
    BALANCED,

    /**
     * Vegetarian plan
     */
    VEGETARIAN,

    /**
     * Vegan plan
     */
    VEGAN,

    /**
     * Diabetic-friendly plan
     */
    DIABETIC_FRIENDLY,

    /**
     * Heart-healthy plan
     */
    HEART_HEALTHY,

    /**
     * Detox / cleanse plan
     */
    DETOX,

    /**
     * Custom plan
     */
    CUSTOM
}

