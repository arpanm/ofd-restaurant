package com.foodai.user.domain.model;

/**
 * Enumeration of meal types in a day.
 *
 * @author FoodAI Team
 */
public enum MealType {
    /**
     * Morning breakfast
     */
    BREAKFAST,

    /**
     * Mid-morning snack
     */
    MORNING_SNACK,

    /**
     * Midday lunch
     */
    LUNCH,

    /**
     * Afternoon snack
     */
    AFTERNOON_SNACK,

    /**
     * Evening dinner
     */
    DINNER,

    /**
     * Late night snack
     */
    LATE_NIGHT_SNACK
}

